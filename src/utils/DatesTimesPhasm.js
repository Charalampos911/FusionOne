console.log("timeStr===",timeStr)

  // 1. Handle "dd-mm-yyyy" format safely
  const [year, month, day] = dateStr.split("-");

  // 2. Normalize time (ensure it has seconds/milliseconds for the full ISO format)
  // If time is "14:30", we append ":00.000"
  const fullTime = timeStr.length === 5 ? `${timeStr}:00.000` : timeStr;

  // 3. Combine into ISO format: YYYY-MM-DDTHH:mm:ss.sssZ
