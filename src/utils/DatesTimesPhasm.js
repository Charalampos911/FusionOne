export function getMinuteDifference(fromTime, untilTime) {
  const [h1, m1] = fromTime.split(':').map(Number);
  const [h2, m2] = untilTime.split(':').map(Number);

  const startTotalMinutes = h1 * 60 + m1;
  const endTotalMinutes = h2 * 60 + m2;

  return endTotalMinutes - startTotalMinutes;
}
