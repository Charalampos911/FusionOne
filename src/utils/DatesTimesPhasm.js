export function getTimesBetween(
  fromDate,
  fromTime,
  untilDate,
  untilTime
) {
  const start = new Date(`${fromDate}T${fromTime}`);
  const end = new Date(`${untilDate}T${untilTime}`);

  const MAX_MINUTES = 24 * 60;
  const INTERVAL = 15;

  const times = [];
  const seen = new Set();

  let current = new Date(start);
  let elapsedMinutes = 0;

  while (current <= end && elapsedMinutes < MAX_MINUTES) {
    const time = current.toTimeString().slice(0, 5); // HH:mm

    if (!seen.has(time)) {
      seen.add(time);
      times.push(time);
    }

    current.setMinutes(current.getMinutes() + INTERVAL);
    elapsedMinutes += INTERVAL;
  }

  return times;
}
export function getTimesFlat(startTime, endTime, isDateTime = false, interval = 15) {
  const result = [];

  if (isDateTime) {
    let current = new Date(startTime);
    const end = new Date(endTime);

    // Ensure we handle valid dates
    if (isNaN(current.getTime()) || isNaN(end.getTime())) return result;

    while (current <= end) {
      // 1. Format local time HH:mm
      const hours = String(current.getHours()).padStart(2, '0');
      const minutes = String(current.getMinutes()).padStart(2, '0');
      const timeLabel = `${hours}:${minutes}`;

      // 2. Format local ISO-like string (YYYY-MM-THH:mm:ss)
      const isoLocal = current.getFullYear() + '-' +
        String(current.getMonth() + 1).padStart(2, '0') + '-' +
        String(current.getDate()).padStart(2, '0') + 'T' +
        timeLabel + ':00';

      result.push([isoLocal, timeLabel]);

      // Step forward by interval
      current = new Date(current.getTime() + interval * 60000);
    }

    return result;
  } else {
    // Helper to parse "HH:mm" or "HH:mm:ss" into total minutes from midnight
    const parseMinutes = (timeStr) => {
      if (!timeStr || typeof timeStr !== 'string') return 0;
      const parts = timeStr.split(':').map(Number);
      return (parts[0] || 0) * 60 + (parts[1] || 0);
    };

    let currentMinutes = parseMinutes(startTime);
    const endMinutes = parseMinutes(endTime);

    // Guard against invalid ranges
    if (isNaN(currentMinutes) || isNaN(endMinutes)) return result;

    while (currentMinutes <= endMinutes) {
      const hours = String(Math.floor(currentMinutes / 60)).padStart(2, '0');
      const mins = String(currentMinutes % 60).padStart(2, '0');
      
      const timeLabel = `${hours}:${mins}`; // "08:30"
      const rawTime = `${timeLabel}:00`;     // "08:30:00"

      // Matches [isoLocal/fullString, timeLabel] schema used by selector UI
      result.push([rawTime, timeLabel]);

      currentMinutes += interval;
    }

    return result;
  }
}


